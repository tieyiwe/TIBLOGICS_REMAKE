export function tipFor(id: string): string | undefined {
  if (TIPS[id]) return TIPS[id];
  const prefix = Object.keys(TIPS).find((k) => k.endsWith("-") && id.startsWith(k));
  return prefix ? TIPS[prefix] : undefined;
}
