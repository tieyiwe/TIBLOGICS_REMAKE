/**
 * French typography: a non-breaking space before : ; ? ! and inside « », so
 * the punctuation never wraps onto a line of its own.
 */
function frenchSpacing(dict: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(dict)) {
    out[k] = v.replace(/ ([:;?!»])/g, " $1").replace(/« /g, "« ");
  }
  return out;
}

